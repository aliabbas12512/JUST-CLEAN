export default async function LegalPage({ params }: { params: Promise<{ doc: string }> }) {
  const { doc } = await params;
  if (doc !== "terms" && doc !== "privacy") notFound();
  const { t, locale } = await getI18n();
  return (
    <div className="mx-auto max-w-3xl space-y-4">
      <PageHeader title={doc === "terms" ? t.legal.termsTitle : t.legal.privacyTitle} />
      <Alert tone="amber">{t.legal.draftNotice}</Alert>
      <Card className="space-y-3 p-5 text-[15px] leading-8 text-slate-700">
        {content[doc][locale].map((p, i) => <p key={i}>{p}</p>)}
      </Card>
    </div>
  );
}
